CATEGORY_WORDS = {
    "اسم": NAMES,
    "حيوان": ANIMALS,
    "بلاد": COUNTRIES,
    "جماد": OBJECTS,
    "نبات": PLANTS,
}


def _variants(word: str):
    w = (word or "").strip()
    if not w:
        return []
    out = {w}
    if w.startswith("ال") and len(w) > 3:
        out.add(w[2:])
    else:
        out.add("ال" + w)
    # تطبيع همزات خفيف
    for a, b in (("أ", "ا"), ("إ", "ا"), ("آ", "ا"), ("ة", "ه"), ("ى", "ي")):
        out |= {x.replace(a, b) for x in list(out)}
    return out


def word_in_category(word: str, category: str) -> bool:
    pool = CATEGORY_WORDS.get(category) or set()
    if not pool:
        return False
    for v in _variants(word):
        if v in pool:
            return True
        # تطابق بعد إزالة مسافات
        vs = v.replace(" ", "")
        for p in pool:
            if p.replace(" ", "") == vs:
                return True
    return False
